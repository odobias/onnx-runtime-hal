<#
.SYNOPSIS
  Package OnnxRuntimeHal as a reusable same-compiler C++ static library.

.DESCRIPTION
  Builds OnnxRuntimeHal.lib for one ORT flavor and copies the public C++ headers,
  import lib, and MSBuild props into dist/onnx-runtime-hal-<arch>-<flavor>/.

  Consumers include <onnx_runtime_hal.hpp>, import the flavor props + 
  OnnxRuntimeHal.props, and link with the same MSVC toolset /MD CRT.
#>
[CmdletBinding()]
param(
    [ValidateSet("Debug", "Release")][string]$Configuration = "Release",
    [ValidateSet("x64", "ARM64")][string]$Architecture = "",
    [ValidateSet("ort", "dml", "winml", "ovep", "amd", "qualcomm")]
    [string]$Flavor = "ort",
    [string]$Output = "",
    [switch]$SkipBuild
)

$ErrorActionPreference = "Stop"
chcp 65001 > $null
[Console]::InputEncoding = [System.Text.UTF8Encoding]::new()
[Console]::OutputEncoding = [System.Text.UTF8Encoding]::new()
$OutputEncoding = [System.Text.UTF8Encoding]::new()

$root = Split-Path (Split-Path $PSScriptRoot -Parent) -Parent
if (-not $Architecture) {
    $Architecture = if (
        [System.Runtime.InteropServices.RuntimeInformation]::OSArchitecture -eq
        [System.Runtime.InteropServices.Architecture]::Arm64
    ) { "ARM64" } else { "x64" }
}

$platformTag = switch ($Flavor) {
    "ort" { $Architecture }
    "dml" { $Architecture }
    "winml" { "$Architecture-winml" }
    "ovep" { "$Architecture-ovep" }
    "amd" { "$Architecture-amd" }
    "qualcomm" { "$Architecture-qualcomm" }
}

if (-not $Output) {
    $Output = Join-Path $root "dist\onnx-runtime-hal-$Architecture-$Flavor"
}
$Output = [IO.Path]::GetFullPath($Output)

$buildArgs = @{
    Configuration = $Configuration
    Platform = $Architecture
}
switch ($Flavor) {
    "ort" {
        $buildArgs.EnableOrt = $true
        $buildArgs.DisableIntel = $true
    }
    "dml" {
        $buildArgs.EnableOrt = $true
        $buildArgs.EnableDirectML = $true
        $buildArgs.DisableIntel = $true
    }
    "winml" {
        $buildArgs.EnableWinML = $true
        $buildArgs.DisableIntel = $true
    }
    "ovep" {
        $buildArgs.EnableOvep = $true
        $buildArgs.DisableIntel = $true
    }
    "amd" {
        $buildArgs.EnableAmd = $true
        $buildArgs.DisableIntel = $true
    }
    "qualcomm" {
        $buildArgs.EnableQualcomm = $true
        $buildArgs.DisableIntel = $true
    }
}

if (-not $SkipBuild) {
    # build.ps1 builds the full solution; OnnxRuntimeHal.lib is produced first via
    # project references from Core/App/Tests.
    & (Join-Path $root "tools\build\build.ps1") @buildArgs
    if ($LASTEXITCODE -ne 0) { throw "OnnxRuntimeHal build failed" }
}

$libPath = Join-Path $root "build\$platformTag\$Configuration\OnnxRuntimeHal.lib"
if (-not (Test-Path -LiteralPath $libPath)) {
    throw "Missing library: $libPath (build the matching flavor first)"
}

if (Test-Path -LiteralPath $Output) {
    Remove-Item -LiteralPath $Output -Recurse -Force
}
$includeOut = Join-Path $Output "include"
$libOut = Join-Path $Output "lib"
$msbuildOut = Join-Path $Output "msbuild"
New-Item -ItemType Directory -Force -Path $includeOut, $libOut, $msbuildOut | Out-Null

# Public headers only — never ship runner/runtime EP internals.
$publicHeaders = @(
    "onnx_runtime_hal.hpp"
    "npu_inference_bench\runtime\device.hpp"
    "npu_inference_bench\runtime\execution_diagnostics.hpp"
    "npu_inference_bench\runtime\precision_policy.hpp"
    "npu_inference_bench\runtime\runtime_options.hpp"
    "npu_inference_bench\runtime\runtime_error.hpp"
    "npu_inference_bench\runtime\tensor.hpp"
    "npu_inference_bench\runtime\model_session.hpp"
    "npu_inference_bench\runtime\runtime_context.hpp"
    "npu_inference_bench\runtime\detail\ort_session_access.hpp"
    "npu_inference_bench\execution_diagnostics.hpp"
    "npu_inference_bench\precision_policy.hpp"
)
$srcInclude = Join-Path $root "runner\include"
foreach ($rel in $publicHeaders) {
    $src = Join-Path $srcInclude $rel
    $dst = Join-Path $includeOut $rel
    New-Item -ItemType Directory -Force -Path (Split-Path $dst -Parent) | Out-Null
    Copy-Item -LiteralPath $src -Destination $dst -Force
}

Copy-Item -LiteralPath $libPath -Destination (Join-Path $libOut "OnnxRuntimeHal.lib") -Force

# Flavor props: point consumers at the matching backend + this package root.
$flavorProps = @"
<?xml version="1.0" encoding="utf-8"?>
<!-- Auto-generated by package-onnx-runtime-hal.ps1 for flavor '$Flavor'. -->
<Project>
  <PropertyGroup>
    <OnnxRuntimeHalRoot>`$(MSBuildThisFileDirectory)..\</OnnxRuntimeHalRoot>
    <OnnxRuntimeHalFlavor>$Flavor</OnnxRuntimeHalFlavor>
    <PlatformOutTag>$platformTag</PlatformOutTag>
  </PropertyGroup>
</Project>
"@
Set-Content -Path (Join-Path $msbuildOut "OnnxRuntimeHal.Flavor.props") -Value $flavorProps -Encoding utf8
Copy-Item -LiteralPath (Join-Path $root "msbuild\OnnxRuntimeHal.props") `
    -Destination (Join-Path $msbuildOut "OnnxRuntimeHal.props") -Force

# Optional: stage runtime-pack helpers for apps that need ORT DLLs beside the exe.
Copy-Item -LiteralPath (Join-Path $root "msbuild\runtime-pack.targets") `
    -Destination (Join-Path $msbuildOut "runtime-pack.targets") -Force

$readme = @"
# OnnxRuntimeHal ($Architecture / $Flavor / $Configuration)

Same-compiler C++23 static library (``LanguageStandard=stdcpp23`` /
``/std:c++23preview``). Include ``onnx_runtime_hal.hpp``, link
``lib\OnnxRuntimeHal.lib``, and import the MSBuild props below with the **same**
MSVC toolset and ``/MD`` (or ``/MDd``) CRT used to build this package.

``````xml
<Import Project="path\to\package\msbuild\OnnxRuntimeHal.Flavor.props" />
<!-- Also import the matching ORT/backend SDK props your app already uses. -->
<Import Project="path\to\package\msbuild\OnnxRuntimeHal.props" />
``````

```cpp
#include <onnx_runtime_hal.hpp>

using namespace onnx_runtime_hal;

RuntimeOptions options;
options.device = Device::NPU;
options.require_requested_device = true;
RuntimeContext ctx(options);
ModelSession session = ctx.load_one(ModelSpec{ model_path });
auto outputs = session.run(inputs);
```

Platform tag: $platformTag
Library: lib\OnnxRuntimeHal.lib
"@
Set-Content -Path (Join-Path $Output "README.md") -Value $readme -Encoding utf8

Write-Host "Packaged OnnxRuntimeHal -> $Output" -ForegroundColor Green
Write-Host "  lib: OnnxRuntimeHal.lib"
Write-Host "  include: onnx_runtime_hal.hpp + runtime/*"
